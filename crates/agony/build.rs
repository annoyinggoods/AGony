//! The agony binary's build script: embed the application icon
//! (`assets/icon.ico`) into the Windows executable, and embed the
//! dependency table for `agony thanks` (Part08 8.4.1) by running
//! `cargo metadata` once per build — the THANK-YOU list is generated,
//! never hand-maintained.
//!
//! Depends on: winresource, serde_json (build-dependencies),
//! assets/icon.ico, the workspace's Cargo.lock.
//! Called by: cargo at build time.
//! Calls: `cargo metadata` (read-only; a failure leaves an empty table
//! and never breaks the build).

use std::process::Command;

fn main() {
    embed_icon();
    embed_dependencies();
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../../Cargo.lock");
    println!("cargo:rerun-if-changed=../../Cargo.toml");
}

fn embed_icon() {
    // The icon is a Windows-executable artifact (winresource compiles a
    // .res); other targets build without it, quietly.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    let icon = std::path::Path::new("assets/icon.ico");
    if !icon.exists() {
        println!("cargo:warning=assets/icon.ico missing — the exe ships without an icon");
        return;
    }
    if let Err(error) = winresource::WindowsResource::new()
        .set_icon(icon.to_str().unwrap_or_default())
        .compile()
    {
        println!("cargo:warning=icon embed failed: {error}");
    }
    println!("cargo:rerun-if-changed=assets/icon.ico");
}

/// (name, version, license) for every package in the workspace's
/// dependency graph, workspace members excluded — `cargo metadata` is
/// the one source, so the table cannot drift from reality.
fn embed_dependencies() {
    let table = dependency_table().unwrap_or_else(|| {
        println!(
            "cargo:warning=cargo metadata failed — THANK-YOU.md will lack the dependency table"
        );
        "[]".to_string()
    });
    let out = std::env::var("OUT_DIR").expect("cargo provides OUT_DIR");
    let path = std::path::Path::new(&out).join("deps_table.rs");
    let code = format!(
        "/// (name, version, license) — generated by build.rs from `cargo \
         metadata`; do not edit (THANK-YOU.md regenerates from it).\npub \
         static DEPENDENCIES: &[(&str, &str, &str)] = &{table};\n"
    );
    if let Err(error) = std::fs::write(&path, code) {
        println!("cargo:warning=deps table write failed: {error}");
    }
}

fn dependency_table() -> Option<String> {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").ok()?;
    let workspace = std::path::Path::new(&manifest)
        .join("../../Cargo.toml")
        .canonicalize()
        .ok()?;
    let output = Command::new(cargo_binary())
        .arg("metadata")
        .arg("--format-version")
        .arg("1")
        .arg("--manifest-path")
        .arg(&workspace)
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let metadata: serde_json::Value = serde_json::from_slice(&output.stdout).ok()?;
    let packages = metadata.get("packages")?.as_array()?;
    let members: Vec<&str> = metadata
        .get("workspace_members")
        .and_then(|value| value.as_array())
        .map(|list| list.iter().filter_map(|entry| entry.as_str()).collect())
        .unwrap_or_default();
    let rows: Vec<String> = packages
        .iter()
        .filter(|package| !is_member(package, &members))
        .map(dependency_row)
        .collect();
    Some(format!("[{}]", rows.join(",")))
}

/// A package is a workspace member when its id appears in
/// `workspace_members` (agony and agony-core themselves).
fn is_member(package: &serde_json::Value, members: &[&str]) -> bool {
    package
        .get("id")
        .and_then(|id| id.as_str())
        .is_some_and(|id| members.contains(&id))
}

fn dependency_row(package: &serde_json::Value) -> String {
    let name = string_field(package, "name");
    let version = string_field(package, "version");
    let license = string_field(package, "license");
    format!(
        "({},{},{})",
        json_string(&name),
        json_string(&version),
        json_string(&license)
    )
}

fn string_field(package: &serde_json::Value, field: &str) -> String {
    package
        .get(field)
        .and_then(|value| value.as_str())
        .unwrap_or("unknown")
        .to_string()
}

/// A JSON string literal is a valid Rust string literal.
fn json_string(text: &str) -> String {
    serde_json::to_string(text).unwrap_or_else(|_| "\"?\"".to_string())
}

fn cargo_binary() -> String {
    std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string())
}
